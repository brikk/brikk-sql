#!/usr/bin/env python3
"""Generate ClickHouse's FunctionCatalog from the vendored system.functions and
system.table_functions dumps.

Sources: vendor/data/clickhouse-functions-26.5.1.1.tsv (name, aggregate kind, case
sensitivity, alias_to) and vendor/data/clickhouse-table-functions-26.5.1.1.tsv (name,
allow_readonly), both captured from ClickHouse 26.5.1.1. Neither exposes signatures, so
overloads stay empty (honest unknown). A name in both is defined once per kind (`file` is a
scalar and a table function). Names starting with `__` are engine internals and are left out.

Usage: python3 tools/generate_clickhouse_functions.py
"""

from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "vendor" / "data" / "clickhouse-functions-26.5.1.1.tsv"
TABLE_SOURCE = ROOT / "vendor" / "data" / "clickhouse-table-functions-26.5.1.1.tsv"
OUT = (
    ROOT / "brikk-sql-metadata" / "src" / "dev.brikk.house.sql.metadata"
    / "GeneratedClickhouseFunctionCatalog.kt"
)


def kstr(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def main() -> None:
    rows = [line.split("\t") for line in SOURCE.read_text().splitlines()[1:]]
    entries: dict[str, dict] = {}
    aliases: list[tuple[str, str]] = []

    for cols in rows:
        if len(cols) < 4:
            continue
        name, is_aggregate, _case_insensitive, alias_to = cols[:4]
        if name.startswith("__"):
            continue
        low = name.lower()
        target = alias_to.lower() if alias_to else ""
        if target and target != low:
            aliases.append((name, target))
            continue
        entries.setdefault(low, {
            "name": name,
            "kind": "AGGREGATE" if is_aggregate == "1" else "SCALAR",
            "aliases": [],
        })

    for alias, target in aliases:
        entry = entries.setdefault(target, {"name": target, "kind": "SCALAR", "aliases": []})
        if alias.lower() != entry["name"].lower():
            entry["aliases"].append(alias)

    table_names = sorted(
        (line.split("\t")[0] for line in TABLE_SOURCE.read_text().splitlines()[1:] if line and not line.startswith("__")),
        key=lambda value: (value.lower(), value),
    )
    tables = [{"name": name, "kind": "TABLE_VALUED", "aliases": []} for name in table_names]
    multi_kind = sorted({t["name"] for t in tables} & {e["name"] for e in entries.values()}, key=str.lower)

    blocks: list[tuple[list[str], int]] = []
    for kind in ("SCALAR", "AGGREGATE", "TABLE_VALUED"):
        pool = tables if kind == "TABLE_VALUED" else entries.values()
        selected = sorted((e for e in pool if e["kind"] == kind), key=lambda e: e["name"].lower())
        blocks.append(([f"    // {kind.lower()} ({len(selected)})"], 0))
        for entry in selected:
            aliases_list = sorted(set(entry["aliases"]), key=lambda value: (value.lower(), value))
            alias_arg = ""
            if aliases_list:
                alias_arg = ", aliases = listOf(" + ", ".join(kstr(a) for a in aliases_list) + ")"
            blocks.append(([
                f"    FunctionDef({kstr(entry['name'])}, FunctionKind.{kind}{alias_arg}),"
            ], 1))

    chunks: list[list[str]] = [[]]
    budget = 0
    for block, cost in blocks:
        if budget + cost > 400 and chunks[-1]:
            chunks.append([])
            budget = 0
        chunks[-1].extend(block)
        budget += cost

    aggregate_count = sum(e["kind"] == "AGGREGATE" for e in entries.values())
    definitions = len(entries) + len(tables)
    alias_count = sum(len(set(e["aliases"])) for e in entries.values())
    lines = [
        "// GENERATED FILE — DO NOT EDIT.",
        "// Generated by tools/generate_clickhouse_functions.py from ClickHouse 26.5.1.1",
        "// system.functions and system.table_functions (vendor/data/clickhouse-functions-26.5.1.1.tsv,",
        "// vendor/data/clickhouse-table-functions-26.5.1.1.tsv), without `__` internals.",
        "// The dumps expose names/kinds/aliases but not signatures; overloads are honestly empty.",
        f"// Defined under two kinds: {', '.join(multi_kind)}.",
        "// ClickHouse is Apache-2.0 licensed. See ATTRIBUTIONS.md and vendor/README.md.",
        "package dev.brikk.house.sql.metadata",
        "",
        f"/** ClickHouse 26.5.1.1 builtins: {definitions} definitions, {alias_count} aliases, "
        f"{aggregate_count} aggregates, {len(tables)} table functions. */",
        "val CLICKHOUSE_FUNCTION_CATALOG: FunctionCatalog = FunctionCatalog(",
        "    " + " + ".join(f"chunk{i}()" for i in range(len(chunks))) + ",",
        "    caseSensitive = true,",
        ")",
    ]
    for i, chunk in enumerate(chunks):
        lines.extend(["", f"private fun chunk{i}(): List<FunctionDef> = listOf(", *chunk, ")"])

    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {definitions} defs / {alias_count} aliases / {len(tables)} table functions -> {OUT}")


if __name__ == "__main__":
    main()
