#!/usr/bin/env python3
"""Generate versioned ClickHouse catalogs from explicit, vendored engine captures.

With no arguments renders every captured version, retaining the historical 26.5 snapshot.
Raw registries expose no machine-readable overloads. Documentation syntax and introduced-in
prose are retained as evidence but never turned into signatures or availability guesses.
"""
import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
DATA = ROOT / "vendor/data"
OUT = ROOT / "brikk-sql-metadata/src/dev.brikk.house.sql.metadata/GeneratedClickhouseFunctionCatalog.kt"


def kstr(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t').replace('\0', '\\u0000') + '"'


def unescape(value):
    if value == r"\N":
        return None
    return re.sub(r"\\(.)", lambda m: {'n': '\n', 't': '\t', 'r': '\r', '0': '\0'}.get(m[1], m[1]), value)


def rows(path):
    header, *body = path.read_text().splitlines()
    return [dict(zip(header.split('\t'), map(unescape, line.split('\t')), strict=True)) for line in body]


def render(data, versions):
    lines = ['// GENERATED FILE — DO NOT EDIT.', '// Generated by tools/generate_clickhouse_functions.py from versioned vendor/data captures.',
             '// Names, kinds, aliases and per-name case policy only; overloads remain unknown.',
             '// ClickHouse is Apache-2.0 licensed. See vendor/README.md and ATTRIBUTIONS.md.',
             'package dev.brikk.house.sql.metadata', '']
    latest = max(versions, key=lambda v: tuple(map(int, v.split('.'))))
    # Keep this getter in the same JVM file class as every prior publication.
    # Kotlin top-level initialization is ordered: the compatibility alias must be a getter.
    lines += [f'val CLICKHOUSE_FUNCTION_CATALOG: FunctionCatalog get() = CLICKHOUSE_{latest.replace(".", "_")}_FUNCTION_CATALOG', '']
    for version in versions:
        ident = version.replace('.', '_')
        source = rows(data / f'clickhouse-functions-{version}.tsv')
        canonical = {r['name'].lower(): r for r in source if not r['alias_to'] and not r['name'].startswith('__')}
        aliases = {}
        for row in source:
            if row['name'].startswith('__'):
                continue
            key = (row['alias_to'] or row['name']).lower()
            canonical.setdefault(key, row)
            if row['alias_to'] and row['name'] != canonical[key]['name']:
                aliases.setdefault(key, []).append(row['name'])
        definitions = []
        for key, row in sorted(canonical.items()):
            name = row['alias_to'] if row['alias_to'] and row['name'].lower() != key else row['name']
            # Prefer the real registered target spelling, not an alias row's spelling.
            real = next((r for r in source if r['name'].lower() == key and not r['alias_to']), None)
            if real:
                name, row = real['name'], real
            kind = 'AGGREGATE' if row['is_aggregate'] == '1' else 'SCALAR'
            a = aliases.get(key, [])
            alias_arg = ', aliases = listOf(' + ', '.join(map(kstr, sorted(set(a)))) + ')' if a else ''
            definitions.append(f'FunctionDef({kstr(name)}, FunctionKind.{kind}{alias_arg})')
        table_rows = rows(data / f'clickhouse-table-functions-{version}.tsv')
        definitions += [f'FunctionDef({kstr(r["name"])}, FunctionKind.TABLE_VALUED)' for r in table_rows if not r['name'].startswith('__')]
        chunks = [definitions[i:i+300] for i in range(0, len(definitions), 300)]
        insensitive = sorted({r['name'] for r in source if r['case_insensitive'] == '1' and not r['name'].startswith('__')})
        lines += [f'/** ClickHouse {version}: {len(definitions)} definitions, {len(insensitive)} case-insensitive registered spellings. */',
                  f'val CLICKHOUSE_{ident}_FUNCTION_CATALOG: FunctionCatalog = FunctionCatalog(',
                  '    ' + ' + '.join(f'clickhouse{ident}Functions{i}()' for i in range(len(chunks))) + ',',
                  '    caseSensitive = true,',
                  '    caseInsensitiveNames = setOf(' + ', '.join(map(kstr, insensitive)) + '),']
        # Pinned batch-4 evidence: a native grammar form, not a system.functions row.
        # 26.8 parses it as an ordinary unknown call and fails at execution instead.
        if version == '26.10.2.103':
            lines += ['    grammarBuiltins = setOf("TRY_CAST"),']
        lines += [')']
        for i, chunk in enumerate(chunks):
            lines += ['', f'private fun clickhouse{ident}Functions{i}(): List<FunctionDef> = listOf(',
                      *('    ' + d + ',' for d in chunk), ')']
        type_file = data / f'clickhouse-types-{version}.tsv'
        if type_file.exists():
            types = rows(type_file)
            lines += ['', f'internal val CLICKHOUSE_{ident}_TYPES: List<TypeDef> = listOf(']
            lines += [f'    TypeDef({kstr(r["name"])}, {kstr(r["alias_to"] or r["name"])}, caseInsensitive = {str(r["case_insensitive"] == "1").lower()}),' for r in types]
            lines += [')']
            settings = rows(data / f'clickhouse-settings-{version}.tsv')
            lines += ['', f'internal val CLICKHOUSE_{ident}_SETTINGS: List<SettingDef> = listOf(']
            settings_by_name = {}
            setting_aliases = {}
            for r in settings:
                key = r['alias_for'] or r['name']
                if key not in settings_by_name or not r['alias_for']:
                    settings_by_name[key] = r
                if r['alias_for']:
                    setting_aliases.setdefault(key, set()).add(r['name'])
            for name, r in sorted(settings_by_name.items()):
                description = f'Default: {r["default"]}. Tier: {r["tier"]}. ' + r['description']
                a = ', aliases = listOf(' + ', '.join(map(kstr, sorted(setting_aliases.get(name, [])))) + ')' if setting_aliases.get(name) else ''
                lines += [f'    SettingDef({kstr(name)}, {kstr(r["type"])}, description = {kstr(description)}{a}),']
            lines += [')']
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', type=pathlib.Path, default=DATA)
    parser.add_argument('--output', type=pathlib.Path, default=OUT)
    parser.add_argument('--version', action='append')
    args = parser.parse_args()
    versions = args.version or [p.name.removeprefix('clickhouse-functions-').removesuffix('.tsv') for p in args.data.glob('clickhouse-functions-*.tsv')]
    versions = sorted(versions, key=lambda v: tuple(map(int, v.split('.'))))
    if not versions:
        parser.error('No ClickHouse function captures')
    args.output.write_text(render(args.data, versions))
    print('Generated ClickHouse snapshots:', ', '.join(versions))


if __name__ == '__main__':
    main()
