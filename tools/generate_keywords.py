#!/usr/bin/env python3
"""Generates the Trino, Doris and ClickHouse keyword catalogs for brikk-sql-metadata.

Sources (vendor/data/<dialect>-keywords-<version>.tsv, columns word, category, token):
  - trino-keywords-483.tsv: `./kotlin run -m metadata-capture -- trino-keywords`, from the
    trino-grammar 483 lexer literals and the parser's `nonReserved` rule.
  - doris-keywords-4.1.4.tsv: `./kotlin run -m metadata-capture -- doris-keywords`, the same
    reading of the vendored Doris 4.1.4 parser jar.
  - clickhouse-keywords-26.5.1.1.tsv: ClickHouse system.keywords (no reservation column, so
    every category is UNKNOWN); see vendor/README.md for the command.

DuckDB keywords come with the DuckDB capture (generate_duckdb_functions.py). This script
only renders rows; categories are decided by the captures.

Usage: python3 tools/generate_keywords.py
"""

from __future__ import annotations

import re

from generate_duckdb_functions import DATA, OUT_DIR, chunked, knullable, kstr, read_dump

OUT = OUT_DIR / "GeneratedKeywords.kt"
DUMP_NAME = re.compile(r"^(trino|doris|clickhouse)-keywords-([\d.]+)\.tsv$")


def main() -> None:
    lines = [
        "// GENERATED FILE — DO NOT EDIT.",
        "// Generated by tools/generate_keywords.py from vendor/data/<dialect>-keywords-<version>.tsv.",
        "// See vendor/README.md and ATTRIBUTIONS.md for provenance and licenses.",
        "package dev.brikk.house.sql.metadata",
    ]
    for path in sorted(DATA.iterdir()):
        if not (m := DUMP_NAME.match(path.name)):
            continue
        dialect, version = m.groups()
        name = f"{dialect.upper()}_{version.replace('.', '_')}_KEYWORDS"
        rows = read_dump(path)
        literals = [
            (f"KeywordDef({kstr(r['word'])}, KeywordCategory.{r['category']}, {knullable(r['token'])})", 4)
            for r in rows
        ]
        expression, functions = chunked(f"{dialect}Keywords", "KeywordDef", literals)
        lines += [
            "",
            f"/** {path.name}: {len(rows)} keywords. */",
            f"internal val {name}: KeywordCatalog = KeywordCatalog({expression})",
            *functions,
        ]
        print(f"{path.name}: {len(rows)} keywords")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
