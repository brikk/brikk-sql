/**
 * Differential test: replays the Python-oracle token corpus (generated by
 * tools/gen_token_corpus.py from sqlglot's identity.sql fixture) against our
 * Tokenizer and requires an exact match of every token.
 */
class TokenCorpusDifferentialTest {

    @Serializable
    private data class OracleToken(
        val type: String,
        val text: String,
        val line: Int,
        val col: Int,
        val start: Int,
        val end: Int,
        val comments: List<String> = emptyList(),
    )

    @Serializable
    private data class OracleCase(val sql: String, val tokens: List<OracleToken>)

    @Serializable
    private data class Corpus(
        val dialect: String,
        val cases: List<OracleCase>,
    )

    private val json = Json { ignoreUnknownKeys = true }

    private fun loadCorpus(name: String): Corpus =
        json.decodeFromString(Corpus.serializer(), testResource("token-corpus/$name"))

    /**
     * brikk extension #52: where the Doris tokenizer deliberately follows the native Doris
     * lexer instead of sqlglot. A corpus mismatch is accepted only when one of these covers
     * it, and each must still diverge from the generated (sqlglot) tables on its probe.
     */
    private enum class DorisNativeLexing(val probe: String, val covers: (String) -> Boolean) {
        UNTAGGED_DOLLAR_STRING("SELECT \$\$a;b\$\$", { "\$\$" in it }),
        NESTED_BLOCK_COMMENT("SELECT 1 /* a /* b */ c */", { Regex("/\\*.*/\\*", RegexOption.DOT_MATCHES_ALL) in it }),
        NESTED_HINT("SELECT /*+ a /* b */ c */ 1", { "/*+" in it && it.indexOf("/*", it.indexOf("/*+") + 3) >= 0 }),
        DASH_COMMENT_BACKSLASH_LF("SELECT 1 -- a\\\n; b", { "--" in it && "\\\n" in it }),
        HASH_IS_NOT_A_COMMENT("SELECT 1 # a", { '#' in it }),
        JINJA_IS_NOT_A_COMMENT("SELECT 1 {# a #}", { "{#" in it }),
    }

    @Test
    fun dorisNativeLexingExceptionsDivergeFromSqlglot() {
        for (exception in DorisNativeLexing.entries) {
            val sqlglot = runCatching { Tokenizer(DorisTokenizerTables.CONFIG).tokenize(exception.probe).map { it.tokenType to it.text } }
            val native = Tokenizer(DorisDialect.LEXICAL_CONFIG).tokenize(exception.probe).map { it.tokenType to it.text }
            if (sqlglot.getOrNull() == native) fail("${exception.name} no longer diverges from sqlglot: ${exception.probe}")
        }
    }

    private fun runCorpus(
        name: String,
        config: TokenizerConfig,
        accepted: (String) -> Boolean = { false },
    ) {
        val corpus = loadCorpus(name)
        check(corpus.cases.isNotEmpty()) { "empty corpus $name" }

        val mismatches = mutableListOf<String>()

        for (case in corpus.cases) {
            val actual = try {
                Tokenizer(config).tokenize(case.sql)
            } catch (e: TokenError) {
                mismatches.add("SQL: ${case.sql}\n  unexpected TokenError: ${e.message}")
                continue
            }

            var caseMismatch: String? = null
            if (actual.size != case.tokens.size) {
                caseMismatch = "token count expected=${case.tokens.size} actual=${actual.size}\n" +
                    "  expected: ${case.tokens.map { it.type to it.text }}\n" +
                    "  actual:   ${actual.map { it.tokenType.name to it.text }}"
            } else {
                for (i in case.tokens.indices) {
                    val exp = case.tokens[i]
                    val act = actual[i]
                    val same = exp.type == act.tokenType.name &&
                        exp.text == act.text &&
                        exp.line == act.line &&
                        exp.col == act.col &&
                        exp.start == act.start &&
                        exp.end == act.end &&
                        exp.comments == act.comments
                    if (!same) {
                        caseMismatch = "token #$i\n" +
                            "  expected: type=${exp.type} text=${exp.text} line=${exp.line} " +
                            "col=${exp.col} start=${exp.start} end=${exp.end} comments=${exp.comments}\n" +
                            "  actual:   type=${act.tokenType.name} text=${act.text} line=${act.line} " +
                            "col=${act.col} start=${act.start} end=${act.end} comments=${act.comments}"
                        break
                    }
                }
            }

            if (caseMismatch != null && !accepted(case.sql)) {
                mismatches.add("SQL: ${case.sql}\n  $caseMismatch")
            }
        }

        if (mismatches.isNotEmpty()) {
            fail(
                "${mismatches.size}/${corpus.cases.size} mismatching cases in $name " +
                    "(showing up to 20):\n\n" +
                    mismatches.take(20).joinToString("\n\n")
            )
        }
    }

    @Test
    fun baseCorpusMatchesPythonOracle() = runCorpus("base.json", TokenizerConfig.BASE)

    @Test
    fun mysqlCorpusMatchesPythonOracle() = runCorpus("mysql.json", MysqlTokenizerTables.CONFIG)

    @Test
    fun dorisCorpusMatchesPythonOracle() = runCorpus("doris.json", DorisTokenizerTables.CONFIG)

    @Test
    fun dorisNativeLexingMatchesPythonOracleExceptNamedDivergences() =
        runCorpus("doris.json", DorisDialect.LEXICAL_CONFIG) { sql -> DorisNativeLexing.entries.any { it.covers(sql) } }

    @Test
    fun starrocksCorpusMatchesPythonOracle() =
        runCorpus("starrocks.json", StarrocksTokenizerTables.CONFIG)

    @Test
    fun prestoCorpusMatchesPythonOracle() = runCorpus("presto.json", PrestoTokenizerTables.CONFIG)

    @Test
    fun trinoCorpusMatchesPythonOracle() = runCorpus("trino.json", TrinoTokenizerTables.CONFIG)

    @Test
    fun duckdbCorpusMatchesPythonOracle() = runCorpus("duckdb.json", DuckdbTokenizerTables.CONFIG)

    @Test
    fun postgresCorpusMatchesPythonOracle() =
        runCorpus("postgres.json", PostgresTokenizerTables.CONFIG)

    @Test
    fun clickhouseCorpusMatchesPythonOracle() =
        runCorpus("clickhouse.json", ClickhouseTokenizerTables.CONFIG)

    @Test
    fun hiveCorpusMatchesPythonOracle() = runCorpus("hive.json", HiveTokenizerTables.CONFIG)

    @Test
    fun spark2CorpusMatchesPythonOracle() = runCorpus("spark2.json", Spark2TokenizerTables.CONFIG)

    @Test
    fun sparkCorpusMatchesPythonOracle() = runCorpus("spark.json", SparkTokenizerTables.CONFIG)

    @Test
    fun bigqueryCorpusMatchesPythonOracle() = runCorpus("bigquery.json", BigqueryTokenizerTables.CONFIG)
}
